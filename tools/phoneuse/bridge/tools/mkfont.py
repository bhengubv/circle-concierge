"""Render printable ASCII from a TTF into 4-bit antialiased bitmaps for the
bridge's screen: main/font_<px>.h. Iosevka is under the SIL Open Font License.

    python3 tools/mkfont.py FONT.ttf 16 22 36
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

src = sys.argv[1]
here = os.path.join(os.path.dirname(__file__), "..", "main")
for px in map(int, sys.argv[2:]):
    font = ImageFont.truetype(src, px)
    asc, desc = font.getmetrics()
    h = asc + desc
    w = max(int(round(font.getlength(chr(c)))) for c in range(32, 127))
    data = []
    for c in range(32, 127):
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((0, 0), chr(c), font=font, fill=255)
        px4 = [v >> 4 for v in im.tobytes()]
        if len(px4) % 2:
            px4.append(0)
        data += [px4[i] << 4 | px4[i + 1] for i in range(0, len(px4), 2)]
    per = (w * h + 1) // 2
    name = f"font{px}"
    with open(os.path.join(here, f"font_{px}.h"), "w") as f:
        f.write(f"// Generated by tools/mkfont.py from {os.path.basename(src)} (SIL OFL) at {px} px.\n")
        f.write("#pragma once\n#include \"display.h\"\n")
        f.write(f"static const uint8_t {name}_bits[] = {{\n")
        for i in range(0, len(data), 24):
            f.write("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",\n")
        f.write("};\n")
        f.write(f"static const font_t {name} = {{ {w}, {h}, {per}, {name}_bits }};\n")
    print(name, w, h, len(data), "bytes")
